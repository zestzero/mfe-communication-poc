import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const registry = JSON.parse(readFileSync(path.join(root, 'config/remotes.json'), 'utf8'));

function exposesOf(remote) {
  return [...remote.exposes, ...(remote.persistent ?? [])];
}

const registryTs = `/* Generated by scripts/generate-remotes.mjs. Do not edit. */
export type RemoteExpose = { export: string; testId: string; loading: string };
export type RemoteDefinition = {
  name: string;
  env: string;
  port: number;
  route: string;
  protected: boolean;
  exposes: RemoteExpose[];
  persistent: RemoteExpose[];
};

export const remoteRegistry = ${JSON.stringify(registry, null, 2)} as RemoteDefinition[];
`;

const importLines = registry.flatMap((remote) =>
  exposesOf(remote).map((expose) => {
    const key = `${remote.name}/${expose.export}`;
    return `  '${key}': () => import('${key}'),`;
  }),
);
const importsTs = `/* Generated by scripts/generate-remotes.mjs. Do not edit. */
export const remoteLoaders = {
${importLines.join('\n')}
};
`;

const modulesTs = `/* Generated by scripts/generate-remotes.mjs. Do not edit. */
${registry
  .flatMap((remote) =>
    exposesOf(remote).map(
      (expose) => `declare module '${remote.name}/${expose.export}' {
  export function ${expose.export}(): JSX.Element;
}`,
    ),
  )
  .join('\n')}
`;

const envLines = registry.map((remote) => `${remote.env}=http://127.0.0.1:${remote.port}/static/mf-manifest.json`).join('\n');
const envFile = `PORT=3000\n${envLines}\n`;

function page(remote) {
  const slots = remote.exposes
    .map(
      (expose) => `      <RemoteReady name="${remote.name}" testId="${expose.testId}">
        <RemoteView id="${remote.name}/${expose.export}" />
      </RemoteReady>`,
    )
    .join('\n');
  return `/* Generated by scripts/generate-remotes.mjs. Do not edit. */
import { useLoaderData } from '@modern-js/runtime/router';
import { RemoteReady, RemoteView } from '../../remotes';

export default function ${remote.name[0].toUpperCase()}${remote.name.slice(1)}Page() {
  const data = useLoaderData() as { route: string; notice?: string | null };
  return (
    <>
      <p data-testid="route-loader">{data.route}</p>
      {data.notice === 'auth' ? <p data-testid="auth-guard">Sign in to open this page.</p> : null}
${slots}
    </>
  );
}
`;
}

function pageData(remote) {
  const route = remote.route.replace(/^\//, '') || 'home';
  if (remote.protected) {
    return `/* Generated by scripts/generate-remotes.mjs. Do not edit. */
import { contextFromRequest } from '@platform/mfe-communication';
import { redirect, type LoaderFunctionArgs } from '@modern-js/runtime/router';

export const loader = ({ request }: LoaderFunctionArgs) => {
  if (contextFromRequest(request).auth.status !== 'authenticated') {
    return redirect('/products?notice=auth');
  }
  return { route: '${route}' };
};
`;
  }
  return `/* Generated by scripts/generate-remotes.mjs. Do not edit. */
import type { LoaderFunctionArgs } from '@modern-js/runtime/router';

export const loader = ({ request }: LoaderFunctionArgs) => ({
  route: '${route}',
  notice: new URL(request.url).searchParams.get('notice'),
});
`;
}

const hostSrc = path.join(root, 'apps/host/src');
mkdirSync(path.join(hostSrc, 'remotes'), { recursive: true });
writeFileSync(path.join(hostSrc, 'remotes/registry.generated.ts'), registryTs);
writeFileSync(path.join(hostSrc, 'remotes/imports.generated.ts'), importsTs);
writeFileSync(path.join(hostSrc, 'remote-modules.d.ts'), modulesTs);
writeFileSync(path.join(root, 'apps/host/.env.example'), envFile);
writeFileSync(path.join(root, 'apps/host/.env'), envFile);

for (const remote of registry) {
  const segment = remote.route.replace(/^\//, '');
  const dir = path.join(hostSrc, 'routes', segment);
  mkdirSync(dir, { recursive: true });
  writeFileSync(path.join(dir, 'page.tsx'), page(remote));
  writeFileSync(path.join(dir, 'page.data.ts'), pageData(remote));
}

console.log(`generated ${registry.length} remotes`);
